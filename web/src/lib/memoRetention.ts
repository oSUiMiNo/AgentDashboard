/**
 * 「いつ消えるか」を人の言葉にする（メモ設計§11-3）。
 *
 * # なぜ固定文言にしないのか
 *
 * 設計§11-3 が名指しで禁じている——**設定で変えた値を反映する（固定文言にすると、
 * 設定を変えた人に嘘を言う）**。要件10 は保持期間を設定で変えられることを求めて
 * いるので、90日のまま「3か月で消えます」と書いてあると、**30日に縮めた人には
 * 3倍の嘘**になる。
 *
 * # なぜ切り出すのか
 *
 * **日を月へ直す規則が、面の中に散ると割れる。** 全体メモとセッションメモは同じ
 * 部品を使う（要件9）が、**文言だけ別に組み立てると片方だけ直る**形になりうる。
 */

/** 1か月とみなす日数。**30日**（暦月ではない——設定は日で持っているため） */
const 月の日数 = 30

/**
 * 保持期間を文にする。
 *
 * | 日数 | 出る字 |
 * |---|---|
 * | 90 | 3か月 |
 * | 30 | 1か月 |
 * | 45 | 45日 |
 * | 7 | 7日 |
 *
 * **月で割り切れるときだけ月で言う。** 45日を「1.5か月」と書くと、
 * **設定した数字が画面のどこにも出てこなくなる**——利用者が自分で入れた値を
 * 確かめられるほうを優先する。
 */
export function 消えるまでの字(retentionDays: number): string {
  // **0 以下は文にしない。** 「0日で消えます」は、消えないのか即消えるのか読めない
  if (!Number.isFinite(retentionDays) || retentionDays <= 0) {
    return ''
  }
  const 日 = Math.floor(retentionDays)
  if (日 % 月の日数 === 0) {
    return `${日 / 月の日数}か月`
  }
  return `${日}日`
}
