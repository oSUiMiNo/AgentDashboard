import { formatBytes } from './format'

/**
 * 大きさの表記（ファイル閲覧の上限を設定から変え、大きいものは流し読みする テスト計画フェーズ6
 * 「TS 側の見本の表が Rust と同じ」）。
 *
 * **Rust 側（`server/crates/protocol/src/fs.rs` の `大きさの表記は画面と同じ見本の表に合う`）と
 * 同じ表。** 断り文（PC が作る）と画面の表記が同じ規則で揃っていることを、両側に同じ表を
 * 置いて固定する——片方だけ直すと片方が落ちる。同点（1.5・2.5・2.25）は「半分は上へ」。
 */
describe('formatBytes', () => {
  it.each([
    [0, '0 B'],
    [1, '1 B'],
    [1_023, '1023 B'],
    [1_024, '1 KB'],
    [1_536, '2 KB'],
    [2_560, '3 KB'],
    [1_048_575, '1024 KB'],
    [1_048_576, '1.0 MB'],
    [2_359_296, '2.3 MB'],
    [3_145_728, '3.0 MB'],
    [5_062_904, '4.8 MB'],
    [8_388_608, '8.0 MB'],
    [104_857_600, '100 MB'],
    [1_073_741_824, '1.0 GB'],
    [21_474_836_480, '20.0 GB'],
    [5_497_558_138_880, '5.0 TB'],
  ])('%d バイトは %s', (bytes, want) => {
    expect(formatBytes(bytes)).toBe(want)
  })
})
