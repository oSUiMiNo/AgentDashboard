/**
 * 押し方の割り当て（並べ替え設計§4-1）。
 *
 * # PC と触る画面で入れ替わる
 *
 * | 押し方 | PC | 触る画面 |
 * |---|---|---|
 * | シングル | **選ぶ** | **開く**。**同じ種類を1つ以上選んでいるときだけ「選ぶ」** |
 * | ダブル | **開く** | —（端末の拡大と取り合う） |
 * | 長押し | — | **選ぶ**（1枚目。以後は同じ種類の集合の中でシングルが「選ぶ」になる） |
 *
 * 入れ替える理由は、**触る画面のダブルタップが端末の拡大と取り合う**こと。開く操作は
 * いちばん頻度が高いので、そこを端末と取り合わせられない。
 *
 * # 何か選んでいる間は、別の種類を押しても「解くだけ」（2026-09-07／09-08・利用者の指定）
 *
 * **押した結果は3通りに分かれる。PC も触る画面も、分かれ方は同じ。**
 *
 * | いま選んでいるもの | 押したもの | 触る画面 | PC |
 * |---|---|---|---|
 * | 何も無い | 何でも | **開く** | **選ぶ** |
 * | 同格（同じ種類で、選べる箱） | それ | **選ぶ** | **選ぶ** |
 * | **別の種類、または選べない箱** | それ | **解くだけ**（`'clear'`） | **解くだけ**（`'clear'`） |
 *
 * **違うのは「何も選んでいないとき」だけ**——触る画面はそこが「開く」で、PC は「選ぶ」
 * （PC は開くのがダブル）。**「解くだけ」の条件は共通**である。
 *
 * **却下したのは「別の種類も選ぶ」案であって、この「解くだけ」ではない。** 差は
 * 「押した相手が選ばれるかどうか」1点だが、そこが分かれ目になる。
 *
 * | | 却下した案 | いまの案 |
 * |---|---|---|
 * | もとの選択 | 消える | 消える |
 * | **押した相手** | **選ばれる** | **選ばれない** |
 * | 遷移 | しない | しない |
 *
 * 却下案は**頼んでいない選択状態へ勝手に移る**——押そうとしたボタンが消えたうえ、
 * 別のボタンに入れ替わる（§5-1 が禁じた事象）。いまの案は**何も選んでいない状態へ
 * 戻る**だけで、これは押した人が意図したことそのものである。
 *
 * 覆した理由は**取り返しのつかなさが釣り合っていない**こと。選択が解けるのは無害で
 * 押し直せば戻るが、画面が切り替わると選んでいたものも見ていた場所も失う。**選択を
 * 解こうとする操作は「やめる」側なので、外したときに何も起きないほうへ倒す。**
 *
 * **開きたければ2回押す**（1回目で解け、2回目は「何も選んでいない」ので開く）。猶予を
 * 置いて「解いた直後は開かない」にはしない——今度は「押したのに開かない」が生まれる。
 *
 * # 選べない箱も「解くだけ」に含める
 *
 * 記録を持たない箱（カードから逆算しただけの枠）は選べない。**選択中でも開く**という
 * 道もあったが採らない。**選べる箱と選べない箱は画面上で見分けが付かない**ので、
 * 同じに見えるものが**あるときは飛び、あるときは飛ばない**ほうが、直す前より悪い。
 * 「解くだけ」は死んだ領域ではない——押せば帯が消え、もう一度押せば開く。
 *
 * **代わりに、選ぶ側へ食い違いが移る。** 枠を何枚か選んでいるときに**記録を持たない枠**を
 * 押すと、選択に足されるのではなく**丸ごと解ける**。残る道は「開く」（＝直したかった事故
 * そのもの）か「何も起きない」（＝死んだ領域）しか無く、**3つのうちいちばん軽い**のが
 * これである——選択が解けるだけなら選び直せるが、飛んだ画面は戻ってこない。
 *
 * # PC も同じにした（2026-09-08。**前の決定を覆している**）
 *
 * **2026-09-07 の時点では、PC を変えないと決めていた。** 理由は「PC はシングルが『選ぶ』
 * なので**そもそも遷移しない**——事故が起きていない」「2回押しが要るようになるだけで
 * 利益が無い」だった。**利用者がこれを承知のうえで覆した。**
 *
 * 覆ったのは重みの置き方である。
 *
 * | 前の見立て | いまの見立て |
 * |---|---|
 * | PC は遷移しないので**事故が起きない** | **遷移だけが事故ではない。** 押した瞬間に帯の中身が入れ替わり、**押そうとしていたボタンが別のボタンになる** |
 * | 2回押しになるのは**損なだけ** | **1回で2つのことが起きるほうが損。** 解除と選択が同時に走ると、どちらを頼んだのか画面から読めない |
 *
 * **もともとこの注釈が「§5-1 が禁じた事象」として名指ししていたのは、この形である**
 * ——「カードの選択が消え・枠が選ばれ・帯の電源が消える」。触る画面についてだけ直して
 * PC を残していたのが、ここで揃った。
 *
 * **選び直したい人は2回押す。** 修飾キーでの近道は作らない——隠れた操作は見つけられず、
 * 押し方の表に載せればいちばん多い「1回押す」の説明が薄まる。**1回目の押しは必ず
 * 目に見える**（地の色が消え、帯そのものが消える）ので、何も起きなかったのと
 * 取り違えることはない。
 *
 * **触る画面には1動作の道がある——長押しである。** 「解くだけ」の状態でも
 * `longPressSelects` は生きていて、400ms 持てば `select()` が種類ごと選び直す。
 * **これは意図である**：長押しは「これを選ぶ」と名指しする操作で、押し間違いの話が
 * 当てはまらない。**タップとは別の操作なので、「解くだけ」を素通りしているのではない。**
 * PC に同じ道が無いのは、PC の長押しに意味を割り当てていないからである。
 *
 * # 判定は1箇所に集める
 *
 * **コンポーネントごとに `if (coarse)` を書かない**（設計§4-1）。2箇所に散った瞬間、
 * 片方だけ直されて画面が食い違う。ここは `window` も `document` も読まない純関数で、
 * 「触る画面か」「いま選択モードか」「その箱は選べるか」を受け取って割り当てを返すだけ。
 */

import type { SelectionKind } from '@/stores/selection'

export interface PressMapping {
  /**
   * シングルで何をするか。
   *
   * - `'open'` … 専用画面へ移る
   * - `'select'` … 選ぶ／外す
   * - `'clear'` … **選択を解くだけ。** 押した相手は選ばれず、遷移もしない
   */
  single: 'select' | 'open' | 'clear'
  /** ダブルで開くか */
  doubleOpens: boolean
  /** 長押しで選べるか */
  longPressSelects: boolean
}

/**
 * その画面での押し方の割り当て。
 *
 * @param coarse 指で触る端末か（`useCoarsePointer()` の結果）
 * @param selecting いま選ばれているものの種類。1つも選んでいなければ `null`
 * @param kind 押されたものの種類
 * @param selectable その箱が選べるか。**記録を持たない箱は選べない**（既定は選べる）
 */
export function pressMapping(
  coarse: boolean,
  selecting: SelectionKind | null,
  kind: SelectionKind,
  selectable = true,
): PressMapping {
  // **同格の集合だけが「選ぶ」を作る。** 選べない箱は、同じ種類でも同格には入らない
  const 同格である = selecting === kind && selectable
  /*
    **「解くだけ」の条件は、PC と触る画面で同じ。**

    ここに `coarse` を持ち込むと、同じ規則が画面ごとに2つできる。**触る画面だけ直した
    ときに実際そうなった**——PC は遷移しないぶん見えにくいが、押した相手が選ばれる
    という同じ事故が残っていた（2026-09-08 に揃えた）。
  */
  const 解くだけ = selecting !== null && !同格である
  if (!coarse) {
    // PC。**開くのはダブルなので、シングルは「選ぶ」か「解く」しかない**
    return { single: 解くだけ ? 'clear' : 'select', doubleOpens: true, longPressSelects: false }
  }
  return {
    // **1枚目を選ぶまではシングルが「開く」。** 何か選んでいる間は、同格なら「選ぶ」、
    // それ以外は「解くだけ」——**遷移は「何も選んでいない」ときにしか起きない**
    single: 解くだけ ? 'clear' : selecting === null ? 'open' : 'select',
    // 触る画面ではダブルを使わない
    doubleOpens: false,
    // **選べない箱は長押しでも選べない。** 規則をここ1箇所に持たせる——`usePress` 側にも
    // 同じ判定を置くと、片方だけ直されて「コメントは選べないと書いてあるのに選べていた」
    // が再発する（`ProjectGroup.test.tsx` の「記録を持たない枠は、長押ししても選ばれない」）
    longPressSelects: selectable,
  }
}

/**
 * 長押しと認める時間（ms）。
 *
 * **Android Chrome 自身の長押し判定が 500ms** なので、同着を避けて手前に置く。
 * iOS Safari は 750ms なので先着する。**実機で決め直す**（設計§13・フェーズ6）。
 */
export const LONG_PRESS_MS = 400

/**
 * 長押しの計測中に動いてよい距離（px）。
 *
 * Android の `TOUCH_SLOP` が 8dip、iOS の `allowableMovement` が 10pt。
 * 超えたら**スクロールと見なして計測をやめる**。**実機で決め直す**（設計§13）。
 */
export const LONG_PRESS_SLOP_PX = 8

/** その移動量で、長押しの計測をやめるか。 */
export function movedTooFar(deltaX: number, deltaY: number): boolean {
  if (!Number.isFinite(deltaX) || !Number.isFinite(deltaY)) {
    // 測れないものは「動いた」に倒す。**押しっぱなしと読み違えるより、
    // スクロールと読み違えるほうが害が小さい**——選ばれないだけで済む
    return true
  }
  return Math.hypot(deltaX, deltaY) > LONG_PRESS_SLOP_PX
}
