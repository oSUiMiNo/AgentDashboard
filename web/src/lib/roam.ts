/**
 * 画面を回遊する効果線の経路（カード設計§9-7）。
 *
 * # 線は、風に飛ばされた紙片である
 *
 * 前の版は「画面内へランダムに散らした4点を巡る」だった。**決めずに作ったので、
 * 動きが何も語っていなかった**（実物を見た利用者の指摘・2026-08-26。設計§9-7-1）。
 *
 * 決めた読みはこう。跳ねたカードの角から紙片がちぎれて飛び出し（①発生）、風に
 * 流され（②飛散）、その場で1回転して向きを変え（③転回）、あとは**画面の構造
 * ——カードとグループの枠の隙間——を縫って漂う**（④回遊）。
 *
 * **回遊が構造をなぞるのが要点である。** ランダムに漂う線は「何かのゴミ」にしか
 * 見えないが、枠の隙間を縫って進む線は「そこに道がある」と読める。
 *
 * # DOM を読む関数と、純関数を分けてある
 *
 * [`measureField`] だけが DOM を読み、[`planRoute`] は数値しか受け取らない。
 * **分けないと単体テストが「何も証明しない経路」を通る**——jsdom の
 * `getBoundingClientRect` は全部 0 を返すので、測る側と決める側が同じ関数に居ると
 * 格子が縮退したまま緑になる。
 *
 * # 座標は「場」に対する位置である
 *
 * 層は一覧のスクロールする入れ物の**内側**（`data-roam-field` の中）に居るので、
 * 線は中身と一緒にスクロールする（設計§9-7-5）。したがってここが返すのは
 * ビューポート座標ではなく**場の左上を原点とする座標**である。
 *
 * # 乱数を使わない
 *
 * `Math.random()` を使うとテストが揺れるし、壊し方を当てても再現しない。
 * **種（`seed`）から決まる**形にしてあるので、同じ種なら必ず同じ経路になる。
 * 見た目のばらつきは、種が線ごとに違うことで出る。
 */

/** 停留点。`x` / `y` は場の左上を原点とする座標 */
export interface RoamStop {
  x: number
  y: number
  /**
   * 進む向き（度）。線は進行方向を向く＝紐が走っていく読みになる。
   *
   * **巻き戻さない。** `atan2` は (-180, 180] しか返さないので、そのまま並べると
   * 輪を1周する途中で +170° → -170° と折り返し、**線が逆回転して見える**。
   * 前の点の角にいちばん近い等価な角を選んで、通し番号で単調に増やしてある。
   */
  r: number
  /** 輪（③転回）の上の点か。**回遊の検査を輪へ当てないため**に印を持つ */
  loop?: boolean
}

/** 場に対する矩形 */
export interface RoamRect {
  x: number
  y: number
  w: number
  h: number
}

/** 跳ねた瞬間に測った、場の様子 */
export interface RoamField {
  /** 場の大きさ（＝層の大きさ＝中身の全高） */
  width: number
  height: number
  /** 跳ねたカードの矩形 */
  card: RoamRect
  /** 通路を立てる材料。カードとグループの矩形 */
  rects: RoamRect[]
}

/**
 * 見える線（窓）の長さ（px）。`stroke-dasharray` の第1引数になる。
 *
 * **線は箱ではなく「経路の一部」である**（設計§23・フェーズ18）。経路ぜんぶを
 * 1本の `<path>` にし、この長さぶんだけ描いて残りを描かない——**窓の中身は
 * 経路そのものの形になる**ので、巻きでは輪の形が出て、角では折れながら曲がる。
 *
 * 30px は利用者の指定（0.1.40 を実物で見て 25→30px。「細く長くすると紐らしくなる」）。
 */
export const ROAM_WINDOW_PX = 30

/**
 * インク（線）の太さ（px）。`stroke-width` になる。
 *
 * 3.5px → 2.5px は利用者の指定（0.1.43 を実物で見て・2026-08-28）。
 */
export const ROAM_INK_PX = 2.5

/**
 * 場の縁から、これだけ内側に留める。
 *
 * **はみ出し防止としては、もう大きすぎる**（2026-08-28・フェーズ18）。箱が消えたので
 * 幾何的に要るのは「線の太さの半分＋丸い端＋うねり」＝ 4px ほどしかない。**それでも
 * 21 に据え置くのは、これが見た目の余白でもあるため**——線が縁に貼り付くと、
 * スクロールバーや枠と喧嘩する。21 はフェーズ11〜14 で実物を見ながら通してきた値
 * （箱の半対角 15.40×1.35 の切り上げ）で、**見た目として実績がある**。
 *
 * スクロール可能オーバーフロー域の話（CSS Overflow 3 §3.5）は変わらず効く——
 * 線がはみ出すとスクロールできる範囲が伸びる。
 */
export const MARGIN = 21

/**
 * 矩形の外側、これだけ離れたところに通路を立てる。
 *
 * カード同士の隙間は 12px（`ProjectGroup` の `gap-3`）なので、**両側から立てた線が
 * ちょうど隙間の中央で重なる**——重複を畳めば「隙間の真ん中を通る道」が1本できる。
 */
const 通路 = 6

/**
 * 経路の停留点の数。**`d` の折れ点の数の出どころ**（フェーズ18 で 61→41）。
 *
 * 減らしたのは要件15-7・15-8（速さ 0.8倍・寿命 70秒）のため——速さは
 * 「総道のり ÷ 寿命」で決まるので、**道のりを 38% 減らすしかない**（設計§23-4）。
 * 1区間 56px は据え置き（「1区間 93px は粗い」の経緯と、行ピッチ 111px の半分という根拠）。
 */
export const ROAM_STOPS = 41

/**
 * ②飛散を何区間で飛ぶか。**固定である。**
 *
 * 前の版は「着地までの距離を [`ROAM_STEP`] で割る」形で 1〜4 と揺れていたが、
 * **区間の数が線ごとに変わると、キーフレームの % を静的に書けない**（設計§9-7-9）。
 * 距離のほうを固定し、**向きだけを種で振る**——フェーズ10 が実測で踏んだのは
 * 「**向き**が揃うと風に見えない」であって、距離ではない。
 *
 * **1 なのは「巻きは発生から1秒後」という指定から出ている**（利用者の指定・2026-08-26）。
 * 等速なので時刻は道のりで決まり、1区間 56px ÷ 25.68px/秒 ＝ **2.18秒**。
 * ここを増やすと巻きが遅れる——**時刻を変えたいときに動かすのはこの数である。**
 */
export const ROAM_FLING = 1

/**
 * ③巻きを何区間で描くか。
 *
 * **少ないと多角形に見え、多いとキーフレームが伸びる。** 媒介変数で等分すると、
 * 弦と実際の曲線のずれは 10 で 0.85px・8 で 1.3px。**3.5px の線に対して 1.3px は
 * 見える**ので 10 を採る。
 *
 * # 幅を 2.5px にしても 10 のまま据え置く（2026-08-28）
 *
 * 上の判断は**3.5px の線**についてのものである。幅が 2.5px になると 0.85px は
 * **線幅の 34%**（3.5px なら 24%）で、**却下した 8 のときの 37% に近づく**
 * （設計§20-4-5 が論点として挙げている）。
 *
 * **それでも動かさない。理由は3つ。**
 *
 * 1. **幾何を据え置くと決めた**（設計§20-2-3 の B 案）。区間の総数は
 *    [`ROAM_STOPS`] − 1 で固定なので、ここを上げるぶん [`ROAM_ROAM`] を
 *    下げるしかない——**「1つも動かさない」に反する**
 * 2. **37% を超えるわけではない**（34%）。近づくだけである
 * 3. **これは見て決めるもの。** 巻きは 0.18〜0.51秒しか映らない。**実物で角ばって
 *    見えたときに動かす**——先回りして動かすと、幅と巻きのどちらが効いたか分からなくなる
 */
export const ROAM_LOOP = 10

/** ④回遊の区間数。**巻きが最初の1区間を食う**ので、歩くのは これ＋1 区間ぶん。
 * フェーズ18 で 49→29（設計§23-4 の表。29 が 0.8倍にいちばん近い＝99.0%） */
export const ROAM_ROAM = 29

/**
 * 1区間の道のり（px）。**ここが速さそのものである。**
 *
 * 停留点を**弧長に比例した %** へ置くので（設計§9-7-9）、区間の長さが揃えば速さも
 * 揃う。前の版は % を等間隔に置いており、**巻きを小さくすると巻きだけ遅くなった**。
 *
 * **56 を据え置く。** 要件が嫌ったのは「1区間 93px は粗い」ことなので、上げずに
 * 点を増やした。カードの行ピッチ 111px がちょうど2区間になる大きさである。
 *
 * 30区間 × 56px ＋ 巻き 117.4px ＝ 1797.4px を 70秒で走るので **25.68px/秒**
 *（要件15-7 の「0.8倍」の 99.0%。区間は整数なので割り切れない。設計§23-4）。
 */
export const ROAM_STEP = 56

/**
 * ③巻きの形（トロコイド）。**進みながら、その場で1回巻く。**
 *
 * `t ∈ [π, 3π]` の局所座標（`u` が進行方向・`v` が法線）で
 *
 * ```
 * u(t) = a(t − π) − b·sin t
 * v(t) = −b(1 + cos t)
 * ```
 *
 * **入口と出口の向きが、どちらもぴったり進行方向を向く**（`u′=a+b, v′=0`）ので
 * 折れ目が出ない。前進は `2πa` ＝ [`ROAM_STEP`] ちょうどで、**巻きは回遊の1区間を
 * 置き換える**——だから巻きが挟まっても、その先の経路は1ピクセルも変わらない。
 *
 * **`b > a` が「線が自分と交差する」条件である**（`b = a` は尖点で接するだけ、
 * `b < a` はただのうねり）。`b = 2a` で、張り出しは 35.7px・交差は前進のちょうど半分
 * のところに1つできる。
 */
const 巻きのa = ROAM_STEP / (2 * Math.PI)
const 巻きのb = 2 * 巻きのa

/**
 * 区間ごとの「呼び値の道のり」。**`roam.css` の % と段数の唯一の出どころである。**
 *
 * キーフレームの % は全部の線で共有される定数表なので、**区間の道のりが種にも場にも
 * 依らず決まっていること**が成立条件になる。飛散を固定し（[`ROAM_FLING`]）、巻きの形を
 * 定数にしたので、この列は常に同じである。
 *
 * 実際の道のりは回遊の脚の刻み方（`round(長 / ROAM_STEP)`）で 0.99〜1.09倍ばらつくが、
 * **段をまたいで系統的にずれない**ことだけが要る——それが「角で減速」の正体だった。
 */
export function roamSpans(): number[] {
  const 弦: number[] = []
  const 点 = (t: number) => ({
    u: 巻きのa * (t - Math.PI) - 巻きのb * Math.sin(t),
    v: -巻きのb * (1 + Math.cos(t)),
  })
  for (let k = 0; k < ROAM_LOOP; k += 1) {
    const p = 点(Math.PI + (2 * Math.PI * k) / ROAM_LOOP)
    const q = 点(Math.PI + (2 * Math.PI * (k + 1)) / ROAM_LOOP)
    弦.push(Math.hypot(q.u - p.u, q.v - p.v))
  }
  return [
    ...Array<number>(ROAM_FLING).fill(ROAM_STEP),
    ...弦,
    ...Array<number>(ROAM_ROAM).fill(ROAM_STEP),
  ]
}

/**
 * 巻き（③）が経路のどこに乗っているかを、道のりの割合で返す。
 *
 * **手で数えない。** 飛散の区間数（[`ROAM_FLING`]）も巻きの区間数（[`ROAM_LOOP`]）も
 * 定数だが、道のりは巻きの形から出ているので、**[`roamSpans`] から引くのが唯一の
 * 出どころ**である。区間の数や寿命を変えても、ここを通していれば追随する。
 *
 * 形を切り替える側（`roam.css` の `roam-curl`）は、**巻きの窓でだけ**線を曲げる
 * ——飛散は幾何的に完全な直線なので、そこで曲げると「道はまっすぐ」と食い違う。
 *
 * @returns `前` ＝ 巻きが始まるまでの割合、`幅` ＝ 巻きが占める割合（どちらも 0〜1）
 */
export function roamLoopWindow(): { 前: number; 幅: number } {
  const 列 = roamSpans()
  const 総 = 列.reduce((a, b) => a + b, 0)
  const 前 = 列.slice(0, ROAM_FLING).reduce((a, b) => a + b, 0)
  const 幅 = 列.slice(ROAM_FLING, ROAM_FLING + ROAM_LOOP).reduce((a, b) => a + b, 0)
  return { 前: 前 / 総, 幅: 幅 / 総 }
}

/** 1本の線が持つコマ（path の変種）の数。**波の位相を 90° ずつ送った4枚** */
export const ROAM_KOMA = 4

/**
 * 手描きの波の個性。**実物の `clip-path` から正弦の当てはめで解いた値**（フェーズ15。
 * 当てはめ誤差 0.002px 未満）を引き継ぐ——**作りが箱から経路へ変わっても、筆致は
 * 変わらない**。振れは半振幅（±px）、波長は px、位相はラジアン。
 *
 * **3種の見分けがここで出る**（「同じ棒が3本並ぶと手書きに見えない」設計§9-7-6）。
 * 箱の時代は `clip-path` の中心線で持っていた性質を、**経路へ焼く波**として持つ。
 */
const 波の個性 = [
  { 振れ: 1.4, 波長: 20, 位相: 0 },
  { 振れ: 1.085, 波長: 12, 位相: (63 * Math.PI) / 180 },
  { 振れ: 1.75, 波長: 30, 位相: (329 * Math.PI) / 180 },
]

/**
 * 停留点の折れ線を密にし、法線方向へ波を焼く（設計§23-5 の決着）。
 *
 * **窓（`stroke-dasharray`）の中身は経路そのものの形になる**ので、手描きらしさは
 * 経路に持たせるしかない。コマ（`koma`）は波の位相を `2π/ROAM_KOMA` ずつ送った変種で、
 * 4枚を `opacity` で切り替えると**波が移動と無関係に歩いて見える**——
 * 「うねった道を通るだけ」に見えない仕掛けはこれである。
 *
 * 返すのは密な点列と、**元の停留点それぞれが密な線のどの弧長に居るか**（節目）。
 * 節目は `stroke-dashoffset` の値の出どころになる。
 */
function 波を焼く(
  stops: RoamStop[],
  shape: number,
  koma: number,
): { 点: { x: number; y: number }[]; 節目: number[] } {
  const 個 = 波の個性[((shape % 波の個性.length) + 波の個性.length) % 波の個性.length]
  const ずれ = (2 * Math.PI * koma) / ROAM_KOMA
  const 点: { x: number; y: number }[] = []
  const 節目: number[] = [0]
  let 弧 = 0
  for (let i = 0; i < stops.length - 1; i += 1) {
    const A = stops[i]
    const B = stops[i + 1]
    const L = Math.hypot(B.x - A.x, B.y - A.y)
    if (L === 0) {
      // 場が縮退して同じ点が続くとき。波を焼く向きが無いので、そのまま置く
      点.push({ x: A.x, y: A.y })
      節目.push(弧)
      continue
    }
    // **6px 刻み。** 波長 12〜30px を折れ線で描くのに足り、`d` が無闇に太らない
    const 分 = Math.max(2, Math.round(L / 6))
    const nx = -(B.y - A.y) / L
    const ny = (B.x - A.x) / L
    for (let j = 0; j < 分; j += 1) {
      const u = j / 分
      const w = 個.振れ * Math.sin((2 * Math.PI * (弧 + L * u)) / 個.波長 + 個.位相 + ずれ)
      点.push({ x: A.x + (B.x - A.x) * u + nx * w, y: A.y + (B.y - A.y) * u + ny * w })
    }
    弧 += L
    節目.push(弧)
  }
  const 尻 = stops[stops.length - 1]
  if (尻 !== undefined) 点.push({ x: 尻.x, y: 尻.y })
  return { 点, 節目 }
}

/**
 * 線1本ぶんの `d` 属性。**座標は CSS 変数ではなくここに直に入る**（`d` は CSS 変数を
 * 使えないため。旧 `routeVars` の後継）。小数第1位まで残す——巻きは 57px しか
 * 広がらないので、1px の丸めで「交差する」が「接する」に潰れる（フェーズ11 の実測）。
 */
export function roamPathData(stops: RoamStop[], shape: number, koma: number): string {
  const { 点 } = 波を焼く(stops, shape, koma)
  const 丸 = (v: number): number => Math.round(v * 10) / 10
  return `M${点.map((p) => `${丸(p.x)} ${丸(p.y)}`).join('L')}`
}

/**
 * 窓の動きの節目（px の弧長）。**`stroke-dashoffset` の値の唯一の出どころ。**
 *
 * | 欄 | 何 |
 * |---|---|
 * | `飛散` | 飛散が終わる弧長（＝巻きの入口） |
 * | `巻き` | 巻きが終わる弧長 |
 * | `終端` | 窓の尻が止まる弧長（全長 − 窓）。ここまで走ると窓の頭が経路の端に着く |
 * | `全長` | 波を焼いた実測の全長。`stroke-dasharray` の第2引数（描かない区間）になる |
 *
 * **コマ0 の波で測る。** 位相を送っても全長はほぼ変わらない（端の半波ぶんだけ）ので、
 * 4枚の窓のずれは 1px 未満に収まる——コマが切り替わる瞬間に窓は飛ばない。
 */
export function roamMilestones(
  stops: RoamStop[],
  shape: number,
): { 飛散: number; 巻き: number; 終端: number; 全長: number } {
  const { 点, 節目 } = 波を焼く(stops, shape, 0)
  let 全長 = 0
  for (let i = 0; i < 点.length - 1; i += 1) {
    全長 += Math.hypot(点[i + 1].x - 点[i].x, 点[i + 1].y - 点[i].y)
  }
  // 節目は「波を焼く前の弧長」なので、実測の全長との比で写す（波で +0.5% ほど伸びる）
  const 素の全長 = 節目[節目.length - 1] || 1
  const 写す = (v: number): number => Math.round((v / 素の全長) * 全長 * 100) / 100
  const 丸全長 = Math.round(全長 * 100) / 100
  return {
    飛散: 写す(節目[Math.min(ROAM_FLING, 節目.length - 1)]),
    巻き: 写す(節目[Math.min(ROAM_FLING + ROAM_LOOP, 節目.length - 1)]),
    終端: Math.max(0, Math.round((全長 - ROAM_WINDOW_PX) * 100) / 100),
    全長: 丸全長,
  }
}

/**
 * 種から 0〜1 の値を作る。
 *
 * **暗号の用途ではない。** ばらけて、同じ種なら同じ値が出ればよい。
 */
function 散らす(seed: number, 回: number): number {
  const x = Math.sin(seed * 12.9898 + 回 * 78.233) * 43758.5453
  return x - Math.floor(x)
}

function 挟む(値: number, 下: number, 上: number): number {
  if (上 < 下) {
    // 場が余白より狭い。真ん中へ寄せる以外にできることが無い
    return (下 + 上) / 2
  }
  return Math.min(上, Math.max(下, 値))
}

/** 近い順に並んだ通路のうち、`値` にいちばん近いものの番号 */
function 近い番号(線: number[], 値: number): number {
  let 番号 = 0
  let 差 = Number.POSITIVE_INFINITY
  線.forEach((座標, i) => {
    const d = Math.abs(座標 - 値)
    if (d < 差) {
      差 = d
      番号 = i
    }
  })
  return 番号
}

/**
 * 飛散の着地を選ぶ。**通路の線の上で、ちょうど1区間ぶん離れた点**を候補にする。
 *
 * **距離が揺れてはいけない。** 飛散は [`ROAM_FLING`] 区間ぶんの道のりを持つと決めて
 * あり（[`roamSpans`]）、実際の距離がそれと食い違うと**そこだけ速さが変わる**——
 * 前の版は狙いの点を通路へ寄せるだけだったので、飛散が 30px まで縮む種があった（実測）。
 *
 * したがって**線の上で距離を解く**。横の通路 `y=c` なら `x = 角.x ± √(D² − (c−角.y)²)`
 * が、ちょうど `D` 離れた点である。縦の通路も同じ。**候補はどれも厳密に `D`** なので、
 * 区間の長さが揃う。
 *
 * **1組（3本）は、扇の中で等間隔に割り当てる**（2026-08-28・要件14-3）。
 * 以前は**1本ずつ独立に籤を引いており、3本は互いを知らなかった**ので、候補が少ない
 * 場面で2本が同じ点へ着いて重なった（0.1.43 を実物で見た利用者の指摘）。
 *
 * **角度そのものを決め打ちにはしない。** 候補は通路の上の点だけで、角度で決めると
 * **通路から外れる**——着いた通路の向きが回遊の初手を決めているので（§9-7-6）、
 * 外れると1歩目で通路を離れる。**候補を角度順に並べ、その中で順位を割り振る**ことで、
 * 放射状に開くことと通路へ着くことの両方が成り立つ。
 *
 * **どの向きの通路へ着いたかを返す。** 横の通路（y）へ着いたなら回遊の初手は横、縦の通路
 * （x）へ着いたなら縦——**着いた線から外れる向きへ動くと、1歩目で通路を離れる。**
 */
function 着地点(
  xs: number[],
  ys: number[],
  角: { x: number; y: number },
  域: 領域,
  seed: number,
  番: number,
  組: number,
): { x: number; y: number; 横: boolean } {
  const D = ROAM_FLING * ROAM_STEP
  // **カードの中へ入る向き以外は、どこへ飛んでもよい。** 角は右上なので、除くのは
  // 左下の四半（+90°〜+180°）だけである。
  //
  // **狭い扇では候補が枯れる。** 飛散は1区間ぶん（56px）しか飛ばないので、そこに届く
  // 通路は「そのカード自身の縁」しか無いことが多い——右上の四半だけに絞ると
  // **12枚並べても候補が0〜2本**になり、1回の跳ねで出る3本が同じ点へ重なる（実測）。
  const 扇の始め = -Math.PI
  const 扇の幅 = (270 * Math.PI) / 180

  const 候補: { x: number; y: number; 横: boolean; θ: number }[] = []
  /*
    **同じ座標を二度入れない**（2026-08-28）。横の通路と縦の通路の両方から**同じ点が
    足される**ことがある。

    **これは下の「候補が足りなければ扇へ逃がす」の前提を守るためのものである**
    ——`候補.length` が「選べる点の数」を意味していないと、閾値の判定が嘘になる。

    **いまの並びでは、これを外しても番人は落ちない**（実測）。重複が実際に起きる
    配置に当たっていないためで、**正しさのために残している**。
  */
  const 既に = new Set<string>()
  const 足す = (x: number, y: number, 横: boolean): void => {
    if (x < 域.左 || x > 域.右 || y < 域.上 || y > 域.下) return
    let θ = Math.atan2(y - 角.y, x - 角.x)
    // 扇は -125°〜+35°。**下側から入る向きだけ +360° して連続にする**
    if (θ > 扇の始め + 扇の幅) θ -= 2 * Math.PI
    if (θ < 扇の始め || θ > 扇の始め + 扇の幅) return
    const 印 = `${x.toFixed(2)},${y.toFixed(2)}`
    if (既に.has(印)) return
    既に.add(印)
    候補.push({ x, y, 横, θ })
  }
  for (const y of ys) {
    const 縦 = y - 角.y
    if (Math.abs(縦) > D) continue
    const 横幅 = Math.sqrt(D * D - 縦 * 縦)
    足す(角.x + 横幅, y, true)
    足す(角.x - 横幅, y, true)
  }
  for (const x of xs) {
    const 横 = x - 角.x
    if (Math.abs(横) > D) continue
    const 縦幅 = Math.sqrt(D * D - 横 * 横)
    足す(x, 角.y + 縦幅, false)
    足す(x, 角.y - 縦幅, false)
  }

  /*
    **候補が組の数に足りないときは、扇へ逃がす**（2026-08-28）。

    飛散は1区間（56px）しか飛ばないので、そこに届く通路は「そのカード自身の縁」しか
    無いことが多い——**12枚並べても候補が0〜2本**になる（実測）。候補が2本しか無い
    ところへ3本を順位で割り振ると、**2本が同じ点へ着く**——0.1.43 を実物で見た
    利用者の指摘（要件14-3）がまさにこれである。

    **扇の中で等間隔に散らした点を使う。** 通路の上ではなくなるが、`歩く` が
    [`近い番号`] でいちばん近い通路へ寄せるので、**2歩目からは格子へ戻る**。
    **重なって出るほうが、初手が1つずれるより悪い。**
  */
  if (候補.length < Math.max(1, 組)) {
    const θ =
      組 > 1 ? 扇の始め + ((番 + 0.5) / 組) * 扇の幅 : 扇の始め + 散らす(seed, 1) * 扇の幅
    return {
      x: 挟む(角.x + Math.cos(θ) * D, 域.左, 域.右),
      y: 挟む(角.y + Math.sin(θ) * D, 域.上, 域.下),
      横: true,
    }
  }

  候補.sort((a, b) => a.θ - b.θ)
  // **1組なら等間隔に割り当てる。** 端から端まで使うので、候補が3つ以上あれば
  // 3本は必ず別の点へ着く。**候補が枯れる場面は残る**（カードが1枚だけ・格子が
  // まばら）——そこは扇を 270° へ広げた緩和が受け持っており、消していない
  const 位置 =
    組 > 1
      ? Math.round((番 * (候補.length - 1)) / (組 - 1))
      : Math.min(候補.length - 1, Math.floor(散らす(seed, 1) * 候補.length))
  const 選 = 候補[位置]
  return { x: 選.x, y: 選.y, 横: 選.横 }
}

/** 歩いてよい範囲。場の余白の内側と、カードのある場所の、両方を満たすところ */
interface 領域 {
  左: number
  右: number
  上: number
  下: number
}

/**
 * 回遊してよい範囲を出す。**カードやグループの枠がある場所だけ**（要件3）。
 *
 * 前の版は場の縁からも通路を立てていたので、**カードが1枚も無い空き地まで縫って
 * いた**——そこに枠は無いのに枠沿いに見える動きをしていた。
 *
 * **`rects` の合併で足りる。** カードは必ずグループの枠の中に描かれるので
 * （`ProjectGroup` の `<section>` の中に `TileGrid` が並べる）、
 * **合併はグループの枠の合併と一致する**。種別を分けて取る必要が無く、測る側
 * （[`measureField`]）にも型にも手を入れずに済む。
 *
 * **矩形が0個なら場の余白の内側そのもの**（縮退）。無いままにすると歩けず、
 * 無限ループか `NaN` が本番でだけ出る。
 */
function 範囲(field: RoamField): 領域 {
  const 場: 領域 = {
    左: MARGIN,
    右: Math.max(MARGIN, field.width - MARGIN),
    上: MARGIN,
    下: Math.max(MARGIN, field.height - MARGIN),
  }
  if (field.rects.length === 0) return 場

  let 左 = Number.POSITIVE_INFINITY
  let 右 = Number.NEGATIVE_INFINITY
  let 上 = Number.POSITIVE_INFINITY
  let 下 = Number.NEGATIVE_INFINITY
  for (const r of field.rects) {
    左 = Math.min(左, r.x - 通路)
    右 = Math.max(右, r.x + r.w + 通路)
    上 = Math.min(上, r.y - 通路)
    下 = Math.max(下, r.y + r.h + 通路)
  }
  return {
    左: 挟む(左, 場.左, 場.右),
    右: 挟む(右, 場.左, 場.右),
    上: 挟む(上, 場.上, 場.下),
    下: 挟む(下, 場.上, 場.下),
  }
}

/**
 * 通路の格子を立てる。
 *
 * 矩形の外側 `通路` px に線を引き、**1px に丸めて重複を畳む**。カード同士の隙間は
 * 両側から立てた線が重なるので、畳んだ結果が「隙間の中央を通る道」になる。
 *
 * **場の縁からは立てない**（要件3）。立てると、カードが1枚も無い空き地にも道ができる。
 * 矩形が0個のときだけ、[`範囲`] の縁＝場の余白の内側を道にする（縮退）。
 */
function 格子(field: RoamField, 域: 領域): { xs: number[]; ys: number[] } {
  const xs = new Set<number>()
  const ys = new Set<number>()
  for (const r of field.rects) {
    xs.add(Math.round(挟む(r.x - 通路, 域.左, 域.右)))
    xs.add(Math.round(挟む(r.x + r.w + 通路, 域.左, 域.右)))
    ys.add(Math.round(挟む(r.y - 通路, 域.上, 域.下)))
    ys.add(Math.round(挟む(r.y + r.h + 通路, 域.上, 域.下)))
  }
  if (xs.size === 0 || ys.size === 0) {
    xs.add(Math.round(域.左))
    xs.add(Math.round(域.右))
    ys.add(Math.round(域.上))
    ys.add(Math.round(域.下))
  }

  return {
    xs: [...xs].sort((a, b) => a - b),
    ys: [...ys].sort((a, b) => a - b),
  }
}

/** 2点の隔たり */
function 隔たり(a: { x: number; y: number }, b: { x: number; y: number }): number {
  return Math.hypot(b.x - a.x, b.y - a.y)
}

/** 角を (-180, 180] へ畳む。**巻き戻しを防ぐための道具** */
function 畳む(度: number): number {
  return ((((度 + 180) % 360) + 360) % 360) - 180
}

/**
 * ③巻き。**進みながら、その場で1回だけ小さく巻く**（要件1・設計§9-7-9）。
 *
 * 入口 `A` から出口 `B` まで、[`巻きのa`] のトロコイドを1周期ぶん描く。`B` は
 * **回遊が置いた最初の点そのもの**なので、巻きが挟まってもその先の経路は1ピクセルも
 * 変わらない——**巻きは回遊の1区間を置き換える**。
 *
 * 前の版は「入口へ戻る円」だった。円は**接するだけで交差しない**うえ、等速のために
 * 半径が区間の長さに縛られ、直径 146px まで膨らんでいた（設計§9-7-8）。
 *
 * **膨らむ側は、範囲の内側へ取る。** 張り出しは 35.7px あるので、通路が範囲の縁に
 * 近いと外側では出てしまう。**前の版のように向きを振って探す必要は無い**——
 * 進む向きは通路の軸に固定されており、選べるのは左右どちらへ膨らむかだけである。
 */
function 巻き(
  A: { x: number; y: number },
  B: { x: number; y: number },
  域: 領域,
  seed: number,
): { x: number; y: number }[] {
  const 伸び = 隔たり(A, B)
  const u = 伸び > 0 ? { x: (B.x - A.x) / 伸び, y: (B.y - A.y) / 伸び } : { x: 1, y: 0 }
  // 法線。**どちらへ膨らませても、入口と出口の向きは進行方向のまま**
  const n = { x: -u.y, y: u.x }

  // 膨らむ側を選ぶ。**範囲の縁までの余地が広いほう**——同じくらいなら種で振る。
  //
  // **符号は下の式と揃える。** 張り出しは `n × (−巻きのb(1+cos t) × 回り)` なので、
  // `回り` が正なら **`−n` の側**へ膨らむ。ここを取り違えると縁のほうへ膨らませてしまい、
  // 挟んだ結果**巻きが一直線に潰れる**（実測で踏んだ——潰れても点の数は合うので、
  // 「点が足りない」では気づけない）
  const 余地 = (回り: number): number => {
    const 先 = {
      x: (A.x + B.x) / 2 - n.x * 回り * 巻きのb,
      y: (A.y + B.y) / 2 - n.y * 回り * 巻きのb,
    }
    return Math.min(先.x - 域.左, 域.右 - 先.x, 先.y - 域.上, 域.下 - 先.y)
  }
  const 右余地 = 余地(1)
  const 左余地 = 余地(-1)
  const 回り =
    Math.abs(右余地 - 左余地) < 1 ? (散らす(seed, 5) < 0.5 ? 1 : -1) : 右余地 > 左余地 ? 1 : -1

  // **縦横とも同じ比率で拡縮する。** 進む向きだけ伸ばすと形が潰れ、弦の比が崩れて
  // 呼び値（[`roamSpans`]）とずれる。回遊の1区間は 56px ちょうどではなく 50〜66px に
  // 揺れるので、ここで相似に保っておくと**弦の比だけは常に同じ**になる
  const 拡 = ROAM_STEP > 0 ? 伸び / ROAM_STEP : 1
  const 出力: { x: number; y: number }[] = []
  for (let k = 1; k <= ROAM_LOOP; k += 1) {
    const t = Math.PI + (2 * Math.PI * k) / ROAM_LOOP
    const 進 = (巻きのa * (t - Math.PI) - 巻きのb * Math.sin(t)) * 拡
    const 横 = -巻きのb * (1 + Math.cos(t)) * 回り * 拡
    出力.push({
      x: 挟む(A.x + u.x * 進 + n.x * 横, 域.左, 域.右),
      y: 挟む(A.y + u.y * 進 + n.y * 横, 域.上, 域.下),
    })
  }
  // **出口は計算し直さず、回遊が置いた点そのものを入れる。** 三角関数で1周させると
  // 数値がわずかにずれ、**そのずれが回遊の全部の点へ伝わる**（フェーズ10 で踏んだ）
  出力[出力.length - 1] = { x: B.x, y: B.y }
  return 出力
}

/**
 * 通路の格子を、[`ROAM_STEP`] ずつ歩く。
 *
 * **`planRoute`（最初に引くとき）と `replanRoute`（途中から引き直すとき）で共有する。**
 * 引き直しは「同じ区間数・同じ呼び値の道のり」でなければならない（設計§20-5-2）ので、
 * **同じ道具で作らないと揃う保証が無い。**
 *
 * `足りた` が偽なら、**要求どおりの道のりで区間を作れなかった**——格子が縮退して
 * いる（場が余白より狭い／通路が消えた）。**引き直しの側はこれを逃げ道の合図に使う**
 * （設計§20-5-5。枚数のような外から決めた閾値は置かない）。
 *
 * **「数が足りたか」だけを見てはいけない。** 動けないときもこの関数は**同じ点を
 * 積んで数だけ揃える**ので、数だけ見ると常に足りたことになる（2026-08-28 に踏んだ）。
 * **動けなかった回があったか**まで見る。
 */
function 歩く(
  xs: number[],
  ys: number[],
  始: { x: number; y: number },
  横0: boolean,
  seed: number,
   本数: number,
  ずらし = 0,
): { 点: { x: number; y: number }[]; 足りた: boolean } {
  let ix = 近い番号(xs, 始.x)
  let iy = 近い番号(ys, 始.y)
  let 横 = 横0
  let 向き = 散らす(seed, 4 + ずらし) < 0.5 ? 1 : -1
  let 現在 = { x: 始.x, y: 始.y }
  const 点: { x: number; y: number }[] = []
  let 残り = 本数
  let 回 = 0
  // **動けなかった回。** 格子が縮退していると、跨いでも同じ点しか返らない
  let 詰まった = false

  while (残り > 0 && 回 < ROAM_STOPS * 4) {
    回 += 1
    const 歩 = 1 + Math.floor(散らす(seed, (回 + ずらし) * 7) * 3)
    for (let n = 0; n < 歩 && 残り > 0; n += 1) {
      // **近すぎる通路は跨いで進む。** 隣り合う枠から立った線は数 px しか離れて
      // いないことがあり、そこで刻むと区間の長さが揃わない
      let 次 = 現在
      for (let 試し = 0; 試し < xs.length + ys.length; 試し += 1) {
        if (横) {
          if (ix + 向き < 0 || ix + 向き >= xs.length) 向き = -向き
          ix = Math.round(挟む(ix + 向き, 0, xs.length - 1))
        } else {
          if (iy + 向き < 0 || iy + 向き >= ys.length) 向き = -向き
          iy = Math.round(挟む(iy + 向き, 0, ys.length - 1))
        }
        次 = { x: xs[ix], y: ys[iy] }
        // **1区間ぶんに近い距離が空くまで跨ぐ。** 半分で妥協すると、round で1区間に
        // 畳まれた短い走りがそのまま「そこだけ遅い区間」になる
        if (隔たり(現在, 次) >= ROAM_STEP * 0.75) break
      }

      const 長 = 隔たり(現在, 次)
      // **1区間の 1/3 も動けなければ、そこは通路が無いのと同じ**（`planRoute` は
      // 同じ点で埋めて先へ進むが、引き直しの側は断る）
      if (長 < ROAM_STEP / 3) 詰まった = true
      const 本来 = Math.max(1, Math.round(長 / ROAM_STEP))
      const 割 = Math.min(残り, 本来)
      for (let k = 1; k <= 割; k += 1) {
        点.push({
          x: 現在.x + (次.x - 現在.x) * (k / 本来),
          y: 現在.y + (次.y - 現在.y) * (k / 本来),
        })
      }
      残り -= 割
      現在 = { ...点[点.length - 1] }
    }

    // **曲がるかどうかだけが予測できない。** 角度は常に直角で、道そのものは読める
    // ——生き物っぽさを経路の乱れではなく分岐の気まぐれで出す（設計§9-7-4）
    if (散らす(seed, (回 + ずらし) * 13) < 0.45) {
      横 = !横
      向き = 散らす(seed, (回 + ずらし) * 17) < 0.5 ? 1 : -1
    }
  }
  return { 点, 足りた: 点.length >= 本数 && !詰まった }
}

/**
 * 点の列へ「次の点を向く角度」を付ける。
 *
 * **巻き戻さない**——前の角にいちばん近い等価な角を選んで単調に増やす。
 * 引き直しのときは、**いま向いている角度から続ける**（`前の角0`）ので線が回らない。
 */
function 向きを付ける(
  点: { x: number; y: number; loop?: boolean }[],
  個数: number,
  前の角0: number,
  最初も向け: boolean,
): RoamStop[] {
  const 出力: RoamStop[] = []
  let 前の角 = 前の角0
  点.slice(0, 個数).forEach((点い, i) => {
    const 次 = 点[i + 1]
    let 生 = 前の角
    if (次 !== undefined) {
      const dx = 次.x - 点い.x
      const dy = 次.y - 点い.y
      // 動かない区間（格子が1本しか無い）は、向きを保つ
      if (dx !== 0 || dy !== 0) 生 = (Math.atan2(dy, dx) * 180) / Math.PI
    }
    const 度 = i === 0 && 最初も向け ? 生 : 前の角 + 畳む(生 - 前の角)
    前の角 = 度
    出力.push(
      点い.loop === true
        ? { x: 点い.x, y: 点い.y, r: 度, loop: true }
        : { x: 点い.x, y: 点い.y, r: 度 },
    )
  })
  return 出力
}

/**
 * 跳ねたカードから飛び出して、輪を描き、枠を縫って回遊する経路を1本ぶん作る。
 *
 * | 停留点 | 何 |
 * |---|---|
 * | 0 | **カードの右上の角**（設計§9-7-2 の①。左上には切り欠きがあるので使わない） |
 * | 1〜 | 風に流された先へ、[`ROAM_STEP`] ずつ（②） |
 * | 続く [`ROAM_LOOP`] 区間 | **輪**。位置が円周を1周し、向きは接線（③） |
 * | 残り | 通路を直進し、角で種由来の確率で直角に曲がる（④） |
 *
 * **すべての区間をほぼ同じ長さにする**（設計§9-7-7 C）。キーフレームの % が等間隔
 * なので、長さが揃えばそのまま等速になる。前の版は距離を見ていなかったので、
 * **曲がり角で減速して見えた**。
 *
 * **道はまっすぐ、紐はパタパタ**（設計§9-7-2）。蛇行させると④の「割と直線的」と
 * 食い違い、①〜③で作った「風に飛ばされた」の読みも消える。
 */
export function planRoute(field: RoamField, seed: number, 番 = 0, 組 = 1): RoamStop[] {
  const 域 = 範囲(field)
  const { xs, ys } = 格子(field, 域)

  // ① 発生——カードの右上の角。**縁から出すので、飛び出しの向きが外側で揃う**
  const 角 = {
    x: 挟む(field.card.x + field.card.w, 域.左, 域.右),
    y: 挟む(field.card.y, 域.上, 域.下),
  }

  // ② 飛散——右上の四半へ、**距離は固定で向きだけ**種ごとに違う（設計§9-7-9）。
  // 着地は通路の線の上で、どちらの向きの通路へ着いたかで回遊の初手が決まる
  const 着地 = 着地点(xs, ys, 角, 域, seed, 番, 組)

  const 点: { x: number; y: number; loop?: boolean }[] = [角]
  for (let n = 1; n <= ROAM_FLING; n += 1) {
    点.push({
      x: 角.x + (着地.x - 角.x) * (n / ROAM_FLING),
      y: 角.y + (着地.y - 角.y) * (n / ROAM_FLING),
    })
  }

  // ④ 回遊——いまの軸へ何本か直進し、角で気まぐれに直角へ折れる。
  // **1本を [`ROAM_STEP`] ごとに割る**ので、長い直進でも速さが変わらない
  //
  // **着いた通路の向きに沿って歩き出す。** 横の通路（y）へ着いたなら横、縦の通路（x）
  // へ着いたなら縦——**着いた線から外れる向きへ動くと、1歩目で通路を離れる**
  //
  // **1区間ぶん多く歩く。** 先頭の1区間は③の巻きが置き換えるので（下記）、
  // ここでは [`ROAM_ROAM`] ＋1 区間ぶんの点を作る
  const { 点: 回遊点 } = 歩く(xs, ys, 着地, 着地.横, seed, ROAM_ROAM + 1)

  // 数が足りない（格子が縮退している）ときは最後の点で埋める。**ここに落ちるのは
  // 場が余白より狭いときだけ**である。**引き直しの側は埋めずに断る**（設計§20-5-5）
  while (回遊点.length < ROAM_ROAM + 1) {
    回遊点.push({ ...(回遊点[回遊点.length - 1] ?? 着地) })
  }

  // ③ 巻き——**回遊の最初の1区間を置き換える**（設計§9-7-9）。
  // 出口は回遊が置いた点そのものなので、**その先の経路は1ピクセルも変わらない**
  for (const 巻き点 of 巻き(着地, 回遊点[0], 域, seed)) {
    点.push({ ...巻き点, loop: true })
  }
  for (const 回遊 of 回遊点.slice(1)) 点.push(回遊)

  // 向きは**次の点へ進む向き**。最後の点だけは、その手前の区間の向きを引き継ぐ
  return 向きを付ける(点, ROAM_STOPS, 0, true)
}

/**
 * 引き直した残りを、いまの道へどう繋ぐか。
 *
 * **いまは1つだけ。** 次のイシュー（カードがぶつかったら効果線が退く）が
 * `'退きながら'` を足す想定で、**引き金と繋ぎ方を足すだけで済む形**にしてある
 * （設計§20-5-3）。**1回しか呼ばれないからといって、この引数を畳まないこと。**
 */
export type RoamJoin = 'すぐ'

/**
 * いまの進み具合（0〜1）から、**いま通過中の区間の番号**を出す。
 *
 * 窓は弧長に対して等速なので、**区間ごとの道のりの累計**がそのまま境目になる
 * （[`roamSpans`]）。返すのは「停留点 i と i+1 のあいだに居る」の i である。
 *
 * **画面を測らない。DOM も読まない。** 進み具合は線の生まれた時刻から計算する
 * ——CSS アニメーションの時計は壁時計なので、経過時間と一致する（設計§23-6）。
 * レイアウトが崩れている最中に `getBoundingClientRect` を足すと、**直そうとしている
 * 見た目そのものを壊す**（設計§20-5-1）。
 */
export function roamSegmentAt(進み: number): number {
  const 道のり = roamSpans()
  const 総 = 道のり.reduce((和, x) => 和 + x, 0)
  let 累 = 0
  for (const [i, 長] of 道のり.entries()) {
    累 += 長
    if (進み < 累 / 総) return i
  }
  return 道のり.length - 1
}

/**
 * **いまの位置と、いまの盤面から、残りの道を引き直す**（設計§20-5-2）。
 *
 * # やらないこと
 *
 * **アニメーションを作り直さない・再起動しない・`currentTime` を巻き戻さない・
 * 継ぎ足さない。** キーフレームの % は全部の線で共有する定数表で、線ごとの違いは
 * CSS 変数の値にしか入っていない——**次の停留点から先の値を書き換えれば、線は
 * その場から新しい向きへ曲がる**（飛ばない）。
 *
 * # 返すもの
 *
 * 停留点 `添字 + 1` 以降ぶん。**いま通過中の区間（`添字` とその手前）は1つも
 * 含まない**——そこを書き換えると、補間の途中で始点が動いて線が飛ぶ。
 *
 * `null` は**逃げ道の合図**（設計§20-5-5）。**要求どおりの区間数を返せないとき**
 * ——通路が消えた、場が狭くなった——にだけ起きる。**枚数のような外から決めた
 * 閾値は置いていない**：`歩く` が足りたかどうかから自然に出る。
 */
export function replanRoute(
  field: RoamField,
  seed: number,
  添字: number,
  現在: { x: number; y: number; r: number },
  繋ぎ: RoamJoin = 'すぐ',
): RoamStop[] | null {
  const 本数 = ROAM_STOPS - 1 - 添字
  if (本数 <= 0) return null
  // 繋ぎ方は1つしか無いが、**引数として受けておく**（次のイシューが足す）
  if (繋ぎ !== 'すぐ') return null

  const 域 = 範囲(field)
  const { xs, ys } = 格子(field, 域)
  if (xs.length === 0 || ys.length === 0) return null

  // **いま向いている向きから、どちらの通路を歩くかを決める。** 横へ進んでいるなら
  // 横の通路——**着いた線から外れる向きへ動くと、1歩目で通路を離れる**
  const ラジアン = (現在.r * Math.PI) / 180
  const 横 = Math.abs(Math.cos(ラジアン)) >= Math.abs(Math.sin(ラジアン))

  // **種をずらす。** ずらさないと、盤面が変わったのに同じ道を辿ろうとする
  const { 点, 足りた } = 歩く(xs, ys, 現在, 横, seed, 本数, 添字 + 1)
  if (!足りた) return null

  // **いま向いている角度から続ける**ので線が回らない。先頭（＝いまの点）は捨てる
  return 向きを付ける([現在, ...点], 本数 + 1, 現在.r, false).slice(1)
}

/* ───────────────── ここから下だけが DOM を読む ───────────────── */

/** 場の様子の控え。**跳ねるたびに測り直さない**（下記） */
let 控え: {
  場: Element
  幅: number
  高さ: number
  矩形: RoamRect[]
  時刻: number
} | null = null

/**
 * 控えを使い回す時間。
 *
 * **後から足すのではなく最初から入れてある**——後付けにすると「跳ねた瞬間の値」と
 * いう前提が途中で変わる。1回の跳ねで出る3本が同じ格子を共有するのは当然として、
 * 跳ねをまたいでも使い回す（枠の並びは 1秒では動かない）。
 */
const 控えの寿命 = 1_000

/** テストが状態を持ち越さないようにする。**製品コードからは呼ばない** */
export function resetField(): void {
  控え = null
}

/**
 * 跳ねた瞬間に1回だけ、場の様子を測る。
 *
 * **読み切ってから書く。** `getBoundingClientRect` が強制するのはレイアウトの1回の
 * フラッシュで、読み取りを連続させれば十数個読んでも1回で済む。間に書き込みを挟むと
 * その回数だけレイアウトが走る（layout thrashing）。
 *
 * **座標は場に対する位置**（`scrollTop` を読まない）。層が場の内側に居るので、
 * 引き算だけで済む——スクロール中に取得のタイミングがずれる事故も起きない。
 */
export function measureField(frame: Element, 測り直す = false): RoamField | null {
  const 場 = frame.closest('[data-roam-field]')
  if (場 === null) return null

  const 場の矩形 = 場.getBoundingClientRect()
  const カード = frame.getBoundingClientRect()

  // **引き直しのときは控えを使わない**（2026-08-28・設計§20-5）。控えは**場の寸法しか
  // 見ていない**ので、**カードが増えても減っても寸法が変わらなければ古い格子を返す**
  // ——引き直しはまさにその変化のために呼ばれるので、そこで古い値を掴むと意味が消える
  const 生きている =
    !測り直す &&
    控え !== null &&
    控え.場 === 場 &&
    控え.幅 === 場の矩形.width &&
    控え.高さ === 場の矩形.height &&
    performance.now() - 控え.時刻 < 控えの寿命

  if (!生きている) {
    const 矩形: RoamRect[] = []
    // **1つの `querySelectorAll` で両方を拾う。** 2回に分けても正しいが、
    // 読む回数を増やす理由が無い
    for (const el of 場.querySelectorAll(
      '[data-testid="tile-shell"],[data-testid="project-group"]',
    )) {
      const r = el.getBoundingClientRect()
      矩形.push({
        x: r.left - 場の矩形.left,
        y: r.top - 場の矩形.top,
        w: r.width,
        h: r.height,
      })
    }
    控え = {
      場,
      幅: 場の矩形.width,
      高さ: 場の矩形.height,
      矩形,
      時刻: performance.now(),
    }
  }

  return {
    width: 場の矩形.width,
    height: 場の矩形.height,
    card: {
      x: カード.left - 場の矩形.left,
      y: カード.top - 場の矩形.top,
      w: カード.width,
      h: カード.height,
    },
    // 控えは共有しているので**渡す前に写す**（受け手が並べ替えても控えが濁らない）
    rects: [...(控え?.矩形 ?? [])],
  }
}
