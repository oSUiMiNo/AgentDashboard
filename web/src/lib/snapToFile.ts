/**
 * **ファイルを選んだら、レールをファイルの面へ寄せる**
 * （`スマホでファイルビュアを開くと画面が崩れる` 設計§5）。
 *
 * # なぜ要るのか
 *
 * レールは左から「ファイルの面 → セッションの面」の順に並ぶ。**セッション側へ払った
 * ままファイルを選ぶと、レールは動かない**——実測で、面を差し込んでも送り位置は変わらない
 * （`overflow-anchor` は横方向には効かない）。**選んだのに何も変わらない**ように見える。
 *
 * # 「開いている1枚が変わったか」では数えない
 *
 * **同じ1枚をもう一度選んでも寄せる。** サイドバーで押すのは「**そのファイルを見たい**」
 * という意思表示なので、いま開いているものと同じかどうかは関係ない。パスの変化で数えると、
 * **セッション側に居るときに同じファイルを押した人が、何も起きないのを見る**ことになる。
 *
 * だから数えるのは**選ばれた回数**である。覚えていた1枚を復元したときや、閉じたときは
 * 増えない——どちらも人が「見たい」と押した瞬間ではない。
 *
 * # 滑らかに動かさない
 *
 * **設計§7 は「静止のときは一瞬で移す」と決めているが、ここでは常に一瞬で移す。**
 *
 * PJT 専用画面のレールは**並べ替えの自動送りと同じもの**なので、`scroll-behavior:
 * smooth` を付けると**掴んでいる間の追従が鈍る**。そして滑らかさを入れなければ、
 * §7 の要求は**自動的に満たされる**——止める分岐も要らない。
 *
 * # `scrollTo` を使わない
 *
 * **jsdom に `Element.prototype.scrollTo` は無い**（実測。`scrollIntoView` だけが
 * `test/setup.ts` でポリフィルされている）。使うと、**後から誰かが単体テストを1本
 * 足しただけで、無関係な例外で落ちる**。`scrollLeft` への代入は jsdom でも動く。
 */
import { useEffect, useRef, type RefObject } from 'react'

/**
 * @param rail 寄せる相手。**まだ無い（描かれていない）ことがある**ので `null` を許す
 * @param 選んだ回数 人がファイルを選んだ回数。**増えたときだけ**寄せる
 * @param 止める `true` の間は寄せない。**PJT 専用画面が並べ替え中に渡す**——
 *   掴んでいる指の下でレールが動くと、掴んだものがずれる
 */
export function useSnapToFile(
  rail: RefObject<HTMLDivElement | null>,
  選んだ回数: number,
  止める = false,
): void {
  const 前の回数 = useRef(選んだ回数)

  useEffect(() => {
    /*
      **止めている間は、何も覚えない。** ここで覚えてしまうと、解けたときには
      「増えていない」ことになり、**保留した寄せが永久に失われる**。並べ替えは
      落としたあとの整定が終わるまで印が立ったままなので、その数百ミリ秒のあいだに
      ファイルを選んだ人が、そのまま取り残される。
    */
    if (止める) {
      return
    }
    if (前の回数.current === 選んだ回数) {
      return
    }
    前の回数.current = 選んだ回数

    const 箱 = rail.current
    if (箱 !== null) {
      箱.scrollLeft = 0
    }
  }, [rail, 選んだ回数, 止める])
}
