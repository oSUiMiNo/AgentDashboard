/**
 * **開いたファイルが変わったら、レールをファイルの面へ寄せる**
 * （`スマホでファイルビュアを開くと画面が崩れる` 設計§5）。
 *
 * # なぜ要るのか
 *
 * レールは左から「ファイルの面 → セッションの面」の順に並ぶ。**寄せる処理が要るのは
 * 1つの場面だけ**である。
 *
 * | 場面 | 送り位置 | 見えるもの |
 * |---|---|---|
 * | 開いていない → 開く | 0 のまま | **ファイル側。何もしなくてよい** |
 * | 開いている・セッション側へ払った → **別のファイルを開く** | **動かない** | セッションのまま |
 *
 * 2つ目が「開いたのに何も変わらない」に見える。**実測で、面を差し込んでも送り位置は
 * 動かないことを確かめてある**（`overflow-anchor` は横方向には効かない）。
 *
 * # 滑らかに動かさない
 *
 * **設計§7 は「静止のときは一瞬で移す」と決めているが、ここでは常に一瞬で移す。**
 *
 * PJT 専用画面のレールは**並べ替えの自動送りと同じもの**なので、`scroll-behavior:
 * smooth` を付けると**掴んでいる間の追従が鈍る**。そして滑らかさを入れなければ、
 * §7 の要求は**自動的に満たされる**——止める分岐も要らない。
 *
 * # `scrollTo` を使わない
 *
 * **jsdom に `Element.prototype.scrollTo` は無い**（実測。`scrollIntoView` だけが
 * `test/setup.ts` でポリフィルされている）。使うと、**後から誰かが単体テストを1本
 * 足しただけで、無関係な例外で落ちる**。`scrollLeft` への代入は jsdom でも動く。
 */
import { useEffect, useRef, type RefObject } from 'react'

/**
 * @param rail 寄せる相手。**まだ無い（描かれていない）ことがある**ので `null` を許す
 * @param 開いている一枚 いま開いているファイルの絶対パス。開いていなければ `null`
 * @param 止める `true` の間は寄せない。**PJT 専用画面が並べ替え中に渡す**——
 *   掴んでいる指の下でレールが動くと、掴んだものがずれる
 */
export function useSnapToFile(
  rail: RefObject<HTMLDivElement | null>,
  開いている一枚: string | null,
  止める = false,
): void {
  /*
    **前に見た1枚を覚える。** 「変わったとき」だけ寄せたいので、値そのものを効果の
    依存にすると**同じ1枚のまま再描画されたときにも寄ってしまう**。
  */
  const 前の一枚 = useRef(開いている一枚)

  useEffect(() => {
    const 変わった = 前の一枚.current !== 開いている一枚
    前の一枚.current = 開いている一枚

    if (!変わった || 開いている一枚 === null || 止める) {
      return
    }
    /*
      **閉じたときは寄せない**（上の `null` の弾き）。閉じるとファイルの面ごと消え、
      送りの範囲が無くなるのでブラウザが勝手に 0 まで戻す——手を出す必要が無い。
    */
    const 箱 = rail.current
    if (箱 !== null) {
      箱.scrollLeft = 0
    }
  }, [rail, 開いている一枚, 止める])
}
