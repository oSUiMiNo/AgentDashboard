/**
 * CLI 自身が持つスラッシュコマンドの表（設計§2-3）。
 *
 * **組み込みのコマンドはディスクのどこにも無い。** 利用者のコマンドもスキルも
 * プラグインもファイルとして数えられるが、`/clear` や `/model` は claude の
 * 実行ファイルの中にあるので、フォルダを何度舐めても出てこない。**数えられない
 * ものは、手で書くしかない。**
 *
 * **先例がある。** `models.ts` が同じ形で、CLI が名乗るものを表として持ち、
 * **表だけを書き換える**作りにしてある。今回もそれに倣う。
 *
 * ## ここに知識を閉じ込める
 * **組み込みの知識を、このファイルの外へ散らさないこと。** 散らすと、CLI の版が
 * 上がったときに直す場所が増え、直し漏れたぶんだけ嘘の候補が残る。集める側
 * （`slashCandidates.ts`）はこの表を「もう1つの出どころ」として受け取るだけで、
 * 中身を知らない。
 *
 * ## この表はずれる
 * **CLI の版が上がれば古くなる。** 消えたコマンドが候補に残り、増えたコマンドは
 * 出ない。**隠さず画面に書く**（設計§6-4）ところまでが今回の範囲で、追随を
 * 自動化するかは決めない（設計§14）。
 *
 * したがって**網羅を狙わない。** 全部載せようとすると、載せ損ねたものと消えた
 * ものの区別が付かなくなるうえ、版ずれの被害だけが増える。**打つ頻度が高く、
 * 名前が安定しているものだけ**を選んである。
 *
 * ## 「組み込みか、同梱スキルか」は問わない
 * 公式には `/doctor` のような**同梱スキル**と `/help` のような**組み込み**が
 * 区別されるが、**打つ人から見れば同じ**である。どちらも実行ファイルの中にあって
 * ディスクから数えられない——**ここに書くかどうかの基準は、その区別ではなく、
 * 上の「打つ頻度が高く、名前が安定しているか」だけ**である。
 */

/** 組み込みコマンド1つ。 */
export interface BuiltinCommand {
  /** `/` に続けて打つ名前 */
  name: string
  /** 一覧の2行目に出す説明 */
  description: string
}

