import { describe, expect, it } from 'vitest'

import { 消えるまでの字 } from './memoRetention'

/*
  **ここが守っているのは §11-3 の「固定文言にしない」である。**

  文言を固定へ戻しても**画面は動く**ので、機械は何も言わない。設定を変えた人だけが
  嘘を読むことになり、**言われるまで気づけない**。
*/

describe('いつ消えるかの文言', () => {
  it('月で割り切れるときは月で言う（既定の90日＝3か月）', () => {
    expect(消えるまでの字(90)).toBe('3か月')
    expect(消えるまでの字(30)).toBe('1か月')
    expect(消えるまでの字(360)).toBe('12か月')
  })

  it('**設定を変えたら文言も変わる。** 90日固定に戻ると、ここが落ちる', () => {
    expect(消えるまでの字(30)).not.toBe(消えるまでの字(90))
  })

  it('割り切れないときは日で言う（設定した数字が画面から消えないように）', () => {
    // 「1.5か月」と書くと、利用者が入れた 45 がどこにも出なくなる
    expect(消えるまでの字(45)).toBe('45日')
    expect(消えるまでの字(7)).toBe('7日')
  })

  it('0 以下は文にしない（消えないのか即消えるのか読めない）', () => {
    expect(消えるまでの字(0)).toBe('')
    expect(消えるまでの字(-1)).toBe('')
    expect(消えるまでの字(Number.NaN)).toBe('')
  })
})
