/**
 * 読み直すと消えるものを抱えた入力欄の台帳（設計§6）。
 *
 * # なぜ要るのか
 *
 * 版が切り替わるとサーバごと入れ替わるので、開いているタブは自分で読み直す。
 * ところが**添付した画像だけは読み直すと消える**——`File` はページを跨いで持てないので、
 * `Composer` は意図して覚えていない（書きかけの文は `lib/drafts.ts` が `localStorage`
 * に置くので消えない）。**消えるものを抱えたタブは、読み直さずに人へ渡す。**
 *
 * 判定するのは `App.tsx` の `ServerChangedBanner` だが、添付は `Composer` の
 * ローカル状態なので親からは見えない。しかも `GroupView` は**カードの数だけ**入力欄を
 * 横並びにする（上限なし）。**どれか1つでも抱えていれば読み直さない**を1箇所で言える
 * 場所が要る。
 *
 * # 鍵はカードではなく、札そのもの
 *
 * 手本の `lib/terminalBridge.ts` は `Map<CardId, …>` で引くが、あちらは**カード単位の
 * 読み手が3つある**（`useSelecting` ／ `sendTerminalKey` ／ `hasWatcher`）ためである。
 * こちらの読み手は [`anyComposerBusy`] **1つだけ**で、しかも問いは「1つでもあるか」。
 * `cardId` を受け取っても**どこからも読まれない値**になるので、取らない。
 *
 * **札を鍵にすると、本人確認が要らなくなる。** `terminalBridge` の `registerTerminal` は
 * 解除のときに `terminals.get(cardId) === send` を確かめている——同じカードで登録し直された
 * とき、古い解除が新しい登録を巻き添えにしないためである。札は登録ごとに別物なので、
 * その道が原理的に無い。**同じ解除を二度呼んでも無害**（`Set.delete` は冪等）。
 *
 * # 既定へ戻すときは、行そのものを消す
 *
 * `false` を置く形にすると、長く開いたタブに**触ったカードの数だけ**行が溜まる
 * （`terminalBridge` の `applySelecting` が同じ理由で行を消している）。ここは
 * `Set.delete` しか無いので、その形にしかならない。
 *
 * # 購読（`useSyncExternalStore`）は作らない
 *
 * 判定は**印が立った瞬間の1回だけ**で、変化を追う必要が無い（設計§6「判定は1度だけ。
 * あとから読み直さない」）。追えるようにすると「添付を1枚外したら画面が飛ぶ」が書けて
 * しまい、要件が退けた形になる——押していない瞬間に画面が入れ替わると、利用者から見れば
 * 「消したら壊れた」に見える。
 */

/**
 * 抱えている入力欄の札。
 *
 * 中身に意味は無く、**登録ごとに別物であること**だけが要る（上の「札を鍵にする」）。
 */
const 抱えている = new Set<object>()

/**
 * 抱えていることを申告する。**返るのは取り下げ。**
 *
 * `useEffect` の `return` にそのまま置ける形にしてある。
 */
export function markComposerBusy(): () => void {
  const 札 = {}
  抱えている.add(札)
  return () => {
    抱えている.delete(札)
  }
}

/** 1つでも抱えていれば真。**判定する側はこれだけ見る。** */
export function anyComposerBusy(): boolean {
  return 抱えている.size > 0
}
