//! 版まわりの環境変数の綴りが、実装とテストの土台で食い違っていないことの門
//! （CICD設計§4）。
//!
//! # なぜ2箇所に同じ文字列があるのか
//!
//! テストが本物のバイナリを起こすときは、**版の切替をあらかじめ無害にしておく**必要が
//! ある（開発者の実環境のポインタを読まない・保管庫へ数十MB を控えにいかない）。その
//! 起こし方は `testkit` に集約してあるが、**testkit から agent-core は参照しない**——
//! あちらが testkit を dev 依存しているので、向きを増やしたくない。
//!
//! そこで綴りは両側に持ち、**片方を直したらもう片方が落ちる**形をここで作る。
//! 記録の置き場所（`STATE_DIR_NAME` など）を消す道と突き合わせているのと同じ考え方。

use agent_core::version;

#[test]
fn 乗り換え済みの印の綴りが土台と一致している() {
    assert_eq!(
        version::VERSION_HANDOVER_ENV,
        testkit::VERSION_HANDOVER_ENV,
        "食い違うと、テストが起こしたバイナリが開発者の実環境のポインタを読む"
    );
}

#[test]
fn 使える構成かの上書きの綴りが土台と一致している() {
    assert_eq!(
        version::VERSION_SUPPORTED_ENV,
        testkit::VERSION_SUPPORTED_ENV,
        "食い違うと、テストのたびに実行ファイル3本ぶんが使い捨ての置き場所へコピーされる"
    );
}
