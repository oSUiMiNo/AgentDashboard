//! 画面配信の稼働条件（セルフホスト化設計§7-2、テスト計画フェーズ4）。
//!
//! # ローカルモードは端末を作らない
//!
//! ローカルモードのブラウザは**同じ PC の中に居る**ので、PTY の生バイトをそのまま
//! 配れる（要件5-1）。そこへ端末エミュレータを挟むと、
//!
//! - セッションごとに CPU（全バイトの解析）とメモリ（画面＋スクロールバック）を食う
//! - 画面を組み直すぶん、生バイトより**遅く・重く**なる（設計§19-2 の実測）
//!
//! という損しかない。フェーズ1 で固めた性能基準（12セッション61fps）の防衛線でもある。
//!
//! 判定は設定キーではなく**報告先**に持たせてある（設計§22 読み替え2）ので、この
//! テストは「ローカルの配線では作れない」ことを配線ごと確かめる形になる。

mod common;

#[tokio::test]
async fn ローカルモードでは端末エミュレータを作らない() {
    let server = common::TestServer::start().await;
    let (session, _watcher) = common::start_session(&server.manager).await;

    assert!(
        session.screen().is_none(),
        "ローカルモードなのに端末エミュレータが作られています（設計§7-2）"
    );

    session.kill();
}
