//! 別の PC のログを引くときに運ぶ型（ログ設計§13・§25）。
//!
//! # なぜ `a2s` の中に置かないのか
//!
//! [`crate::fs`] とまったく同じ事情である。ここの型は**2つの線を流れる**——
//! セッションホスト → サーバは A2S（[`crate::a2s`]）だが、サーバ → ブラウザと
//! サーバ → CLI は REST の応答になる。片方の線のモジュールへ置くと、もう片方が
//! 「相手の線の型」を名指しすることになり、どちらが持ち主なのか読めなくなる。
//!
//! # 上限は型と同じ場所に置く
//!
//! 守るのはセッションホストだが、**断り文を出すのはサーバと読み手**なので、値の綴りが
//! 散りやすい。ここに1つだけ置いて全員が引く。
//!
//! # 運ぶのは「生の1行」であって、解いた形ではない
//!
//! [`LogChunk::lines`] は `<state_dir>/logs/` のファイルにある1行をそのまま持つ。
//! 解いて構造体で運ぶと、受け側が組み立て直したときに**欄の並びが変わる**——
//! `session_host_core::logging` は「7欄を書いた順に出す」ことを明示的な設計に
//! しているので、同じ行が「その機械で読むと `ts,level,…`、引いて読むと別の順」に
//! なってしまう。生で運べば、読み手は既にある1本の経路（解く → 絞る → 出す）に
//! そのまま乗せられる。

use serde::{Deserialize, Serialize};

/// 1回の問いで返す行数の上限（設計§25-1）。
///
/// 足りなければ `since` を進めて何度でも引ける。**1回で全部返そうとしない**——
/// 線の向こうの答えは、待たせる時間そのものになる。
pub const MAX_LOG_LINES: usize = 2_000;

/// 1回の問いで返す大きさの上限（設計§25-1）。
///
/// **行数と重ねて掛ける。** 1行は `tail` 欄（端末の末尾）のせいで数 KB になりうるので、
/// 行数だけでは縛れない。値は [`crate::fs::MAX_LISTING_BYTES`] と揃えてある——
/// 同じ答えの道（`acct:{id}:events`）を流れるものが、既にその大きさで通っている。
pub const MAX_LOG_BYTES: usize = 512 * 1024;

/// 水位の名前。**低いほうから並べてある**（順位そのものが意味を持つ）。
///
/// ここに置くのは、**読める値かどうかを見る場所が2つある**ため。切り出すのは
/// セッションホスト（`session_host_core::logs`）だが、**投げる前に断るのはサーバ**
/// （`server_core::hosts`）である。同じ綴りを2箇所に書くと、片方だけ増えたときに
/// 「サーバは通すのに PC が断る」という、呼んだ側から見て理由の分からない形になる。
///
/// 実際にそうなっていた——`level` だけ検証されずに投げられ、PC 側で落ちて 415 になり、
/// **呼ぶ側の打ち間違いが相手の PC の落ち度として報告されて**いた。
///
/// **線の形ではない。** 増減しても互換は壊れないが、増やすなら書き手（`logging`）の
/// 側と揃っていることを確かめること。
pub const LEVELS: &[&str] = &["TRACE", "DEBUG", "INFO", "WARN", "ERROR"];

/// どの行が欲しいか（設計§25-2）。
///
/// # なぜ CLI の引数の型をそのまま送らないのか
///
/// `session_host_core::logs::LogsArgs` には **`state_dir` が入っている**。あれを線に
/// 載せると `GET /api/hosts/{id}/logs?state_dir=/etc` が**別の機械の任意の場所を読む口**に
/// なる。`follow` / `json` / `host` も「受け取った側がどう出すか」の話であって、
/// 相手への頼みではない。**渡す欄を数え上げて決める**のが、この型が別に在る理由。
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LogQuery {
    /// これより前の `ts` は要らない。**絶対時刻（RFC3339・ミリ秒・UTC）へ解決済み。**
    ///
    /// `1h` のような相対の綴りを送って相手に解決させてはいけない。**時計のずれが
    /// 完全に見えなくなる**（設計§25-4）。こちらの時計で解いて送れば、ずれは
    /// 「思ったより多い・少ない」という観測できる形で現れる。
    pub since: String,
    /// この水位以上だけ（`TRACE` / `DEBUG` / `INFO` / `WARN` / `ERROR`）
    pub level: String,
    /// このセッションの行だけ
    pub card: Option<String>,
    /// このプロセスの行だけ（`dashboard` / `session-host` / `browser` / `browser-anon`）
    pub proc: Option<String>,
    /// 正規表現で絞る。**相手側で当てる。**
    ///
    /// 受け取ってから当てると、上限で切られた 2,000 行に当てることになり、
    /// 「一致が少ない」のか「切られた先に在った」のかが**読み手から区別できない**。
    pub grep: Option<String>,
    /// `grep` を当てる先。真なら生の1行、偽なら人が読む形に整えた1行。
    ///
    /// 運ぶ形は常に生だが、**当てる先まで生に固定すると `--grep` の意味が構成で変わる**。
    /// 手元では `--json` の有無で当てる先が変わるので、それをそのまま伝える。
    pub grep_on_raw: bool,
    /// 外へ貼るために伏せるか。**伏せるのは相手側の仕事。**
    ///
    /// 伏せる規則は「その機械の」環境（ホーム・利用者名・ホスト名・アカウント）から
    /// 組む。こちらで組んで相手の行に当てても、相手の利用者名もホーム名も規則に
    /// 入っていないので、**「伏せたつもり」が素通しになる**（設計§25-7）。
    pub sanitize: bool,
}

/// 引いてきたログ（設計§25-1）。
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LogChunk {
    /// どの PC のものか。**埋めるのはサーバ**で、PC は空のまま返す。
    ///
    /// PC は自分がどの綴りで呼ばれたかを知らない（自分の名前は名乗れるが、
    /// アカウントを跨ぐと一意でない）。知っているのは頼みを受けた側なので、
    /// そちらが埋める。
    pub host: String,
    /// 答えた瞬間の、**その PC の時計**（RFC3339・ミリ秒・UTC）。
    ///
    /// 読み手は自分の時計と比べて、ずれていれば警告を出せる。設計§18-7 が
    /// 「`host` を出せば読み手が扱えるか、駄目なら受け取った側の時刻も併記する」と
    /// していたものの答えで、**併記する側を採った**（設計§25-4）。
    pub host_now: String,
    /// 生の JSON Lines。**1要素が1行**で、改行は含まない。
    pub lines: Vec<String>,
    /// 上限で打ち切ったか。**隠さない**（[`crate::fs::DirListing::truncated`] と同じ約束）
    pub truncated: bool,
    /// 読めなかったものの数（**行**と、開けなかった**ファイル**を1件ずつ数える）。
    ///
    /// **引いたときだけ黙らない**——手元で読むときは「読めない行を N 行飛ばしました」
    /// と必ず言うので、跨いだら消えるのでは片手落ちになる。行とファイルを分けて
    /// 数えないのは、読み手がすることが同じだから（**この答えは全部ではない**）
    pub broken: u32,
    /// 伏せ切れなかったものの数（`sanitize` のときだけ意味を持つ）。
    ///
    /// 0 でないことは「外へ貼ってはいけない」の合図なので、**必ず読み手まで運ぶ**。
    pub leaks: u32,
}

#[cfg(test)]
mod tests {
    #![allow(non_snake_case)]

    use super::*;

    #[test]
    fn 上限は行数と大きさの二重で掛かる() {
        // 設計§25-1 と食い違ったら、どちらかが嘘になっている
        assert_eq!(MAX_LOG_LINES, 2_000);
        assert_eq!(MAX_LOG_BYTES, 524_288);
        // 答えの道を共有しているので、既にそこを通っている大きさを超えない
        assert_eq!(MAX_LOG_BYTES, crate::fs::MAX_LISTING_BYTES);
    }

    #[test]
    fn 頼みにstate_dirが入っていない() {
        // **この型が別に在る理由そのもの。** CLI の引数をそのまま線に載せると、
        // 別の機械の任意の場所を読む口になる（設計§25-2）
        let query = LogQuery {
            since: "2026-08-08T00:00:00.000Z".to_string(),
            level: "INFO".to_string(),
            card: None,
            proc: None,
            grep: None,
            grep_on_raw: false,
            sanitize: false,
        };
        let json = serde_json::to_string(&query).unwrap();
        assert!(!json.contains("state_dir"), "{json}");
        assert!(!json.contains("follow"), "{json}");
        assert!(!json.contains("host"), "{json}");
    }
}
